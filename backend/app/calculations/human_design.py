def get_hd_type(birth_date: str) -> str:
    from app.calculations.numerology import calculate_life_path
    result = calculate_life_path(birth_date)
    if "error" in result:
        return "Генератор"
    lp = result["number"]
    return HD_TYPE_BY_LIFE_PATH.get(lp, "Генератор")


def hd_compatibility(type1: str, type2: str) -> int:
    key = (type1, type2)
    if key in HD_COMPAT:
        return HD_COMPAT[key]
    key_rev = (type2, type1)
    if key_rev in HD_COMPAT:
        return HD_COMPAT[key_rev]
    return 68
